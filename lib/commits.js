'use strict';

// Finds the commits a Bash `git commit` call created, so extract.js can count the
// lines of code written through heredocs and `sed -i`, which Edit and Write results
// never show. The transcript's own commit output is never parsed: rtk rewrites it
// to `ok N files changed` or just `ok`. The commits are read back from git instead.

const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');
const { bashGroup } = require('./transcript-lines');
const { findRepo } = require('./repo');

// Lines of these files are generated by tools, so they count 0.
const LOCKFILES = new Set(['package-lock.json', 'pnpm-lock.yaml', 'yarn.lock', 'Cargo.lock']);

// Removes heredoc bodies from `command`. For each `<<[-~]?WORD` operator (WORD may be
// quoted) the lines after the operator's line, through the line that is exactly WORD
// (leading tabs ignored for `<<-`), are dropped, or all remaining lines when none ends it.
// The operator line stays, so `git commit -F - <<'EOF'` is still a commit segment. Text
// inside the body is data, so a `git merge --squash x` line in a file the command writes
// is not a command. A `<<` inside quoted text on a line is read as an operator too.
function blankHeredocs(command) {
  const lines = String(command || '').split('\n');
  const out = [];
  for (let i = 0; i < lines.length; i++) {
    out.push(lines[i]);
    const delimiters = [...lines[i].matchAll(/(?<!<)<<(-?)[~]?\s*(['"]?)(\w+)\2/g)].map((m) => ({ word: m[3], tabs: m[1] === '-' }));
    for (const { word, tabs } of delimiters) {
      let end = i + 1;
      while (end < lines.length && (tabs ? lines[end].replace(/^\t+/, '') : lines[end]) !== word) end++;
      i = end;
    }
  }
  return out.join('\n');
}

// The parts of a command that run one after another, split on && || ; | and newlines.
// Each part is { text, open, close }: `text` without its leading `(` and trailing `)`,
// `open` the count of leading `(` and `close` the count of trailing `)`.
function parts(command) {
  return blankHeredocs(command).split(/&&|\|\||[;|\n]/).map((raw) => {
    const s = raw.trim();
    const open = /^[\s(]*/.exec(s)[0].split('(').length - 1;
    const body = s.replace(/^[\s(]+/, '');
    // A trailing `)` closes a subshell only when no `(` in the segment matches it, so
    // `git commit -m fix(x)` closes nothing. A `(` inside quotes does not count, so
    // `(cd /a && git commit -m "fix(x)")` still closes its subshell.
    const close = Math.max(0, /\)*$/.exec(body)[0].length - (blankQuotes(body).split('(').length - 1));
    return { text: body.slice(0, body.length - close).trim(), open, close };
  }).filter((p) => p.text);
}

function segments(command) {
  return parts(command).map((p) => p.text);
}

// Replaces quoted text with `""`, so words inside a commit message are not read as options.
function blankQuotes(command) {
  return String(command || '').replace(/"(?:[^"\\]|\\.)*"|'[^']*'/g, '""');
}

// The number of `git commit --amend` segments in `command`, and the number of rebase or
// pull segments that come before the first of them. Quoted text is blanked first, so
// `-m "docs: explain --amend"` does not count.
function amendInfo(command) {
  const segs = segments(blankQuotes(blankHeredocs(command)));
  const amendAt = [];
  let firstRewrite = -1;
  segs.forEach((s, i) => {
    const group = bashGroup(s);
    if (group === 'git commit' && /(?:^|\s)--amend(?:\s|$)/.test(s)) amendAt.push(i);
    if ((group === 'git rebase' || group === 'git pull') && firstRewrite < 0) firstRewrite = i;
  });
  return { amendAt, firstRewrite };
}

// True when a `git commit` segment keeps an older author time on purpose: --date,
// -C/-c/--reuse-message/--reedit-message (the words after `commit`, not `git -C <path>`).
function keepsAuthorTime(command) {
  return segments(blankQuotes(blankHeredocs(command))).some((s) => {
    if (bashGroup(s) !== 'git commit') return false;
    const m = COMMIT_WORDS.exec(s);
    return !!m && /(?:^|\s)(?:--date(?:=|\s|$)|-[Cc]|--reuse-message|--reedit-message)/.test(m[2]);
  });
}

// The git subcommands that create a non-merge commit. A rebase (also through `--exec` of
// a script that amends), cherry-pick, revert, am and pull (--rebase) make commits that
// resolveCommits reads back as rewrite or reflog rows. `merge` is left out: it creates
// only merge commits (dropped by `--no-merges`) or nothing, and a `merge --squash` call
// would take the commit of the next call as its own row and use up its squash mark.
const CREATING_VERBS = ['commit', 'rebase', 'cherry-pick', 'revert', 'am', 'pull'];

// True when any segment of `command` is a commit-creating git call (CREATING_VERBS, also
// through rtk or `git -C`).
function isCommitCommand(command) {
  return segments(command).some((s) => CREATING_VERBS.some((v) => bashGroup(s) === `git ${v}`));
}

// The first word of `text` with one layer of quotes removed, and `~` expanded.
function firstPath(text) {
  const m = /^(?:"([^"]*)"|'([^']*)'|(\S+))/.exec(text.trim());
  if (!m) return null;
  const p = m[1] ?? m[2] ?? m[3];
  if (p === '~' || p.startsWith('~/')) return path.join(os.homedir(), p.slice(1));
  return p;
}

// `git [-C path | -c k=v]... commit` in a segment: [1] holds the options before `commit`,
// [2] the words after it. A `-C` in [2] is the reuse-message option, not a directory.
const COMMIT_WORDS = /(?:^|\s)git\s+((?:-[Cc]\s+(?:"[^"]*"|'[^']*'|\S+)\s+)*)commit(?:\s+([\s\S]*))?$/;
// The same for any other git subcommand.
const wordsOf = (verb) => (verb === 'commit' ? COMMIT_WORDS : new RegExp(`(?:^|\\s)git\\s+((?:-[Cc]\\s+(?:"[^"]*"|'[^']*'|\\S+)\\s+)*)${verb}(?:\\s+([\\s\\S]*))?$`));

// The directories `command`'s `git <verb>` segments run in, one per segment that
// `accept` takes, in order, without duplicates. Each segment's directory is the last
// `cd` before it, then its own `git -C`, resolved against `cwd`. A `(` pushes the current
// directory and a `)` pops it, so the `cd` in `(cd /a) && git commit` does not reach the
// commit. Paths that do not resolve to an absolute path are left out.
function gitDirs(command, cwd, verbs, accept) {
  const dirs = [];
  for (const { dir } of gitSegments(command, cwd, verbs, accept)) if (!dirs.includes(dir)) dirs.push(dir);
  return dirs;
}

// The segments of `command` that gitDirs lists, in order and without removing duplicates:
// { dir, text, verb }.
function gitSegments(command, cwd, verbs, accept) {
  const stack = [cwd];
  const found = [];
  const resolve = (dir, target) => (dir || path.isAbsolute(target) ? path.resolve(dir || '/', target) : null);
  for (const { text, open, close } of parts(command)) {
    for (let i = 0; i < open; i++) stack.push(stack[stack.length - 1]);
    const cd = /^cd\s+(.+)$/.exec(text);
    if (cd) {
      const target = firstPath(cd[1]);
      if (target) stack[stack.length - 1] = resolve(stack[stack.length - 1], target);
    } else if (verbs.some((v) => bashGroup(text) === `git ${v}`) && accept(text, bashGroup(text).slice(4))) {
      let dir = stack[stack.length - 1];
      const m = wordsOf(bashGroup(text).slice(4)).exec(text);
      for (const c of m ? m[1].matchAll(/-C\s+("[^"]*"|'[^']*'|\S+)/g) : []) {
        const target = firstPath(c[1]);
        if (target) dir = resolve(dir, target);
      }
      if (dir && path.isAbsolute(dir)) found.push({ dir, text, verb: bashGroup(text).slice(4) });
    }
    for (let i = 0; i < close && stack.length > 1; i++) stack.pop();
  }
  return found;
}

// The directories `command`'s commit-creating git calls (CREATING_VERBS) run in, in order.
// See gitDirs. Re-record and squash marking stays keyed to `git commit` segments
// (resetEvents).
function commitDirs(command, cwd) {
  return gitDirs(command, cwd, CREATING_VERBS, () => true);
}

const UNSQUASH_VERBS = ['merge', 'reset', 'checkout', 'switch', 'stash', 'restore'];

// True for a segment that drops a staged squash: `git merge --abort`, `git reset`,
// `git checkout`, `git switch`, `git stash` and `git restore --staged`.
function dropsSquash(text, verb) {
  const t = blankQuotes(text);
  if (verb === 'merge') return /(?:^|\s)--abort(?:\s|$)/.test(t);
  if (verb === 'restore') return /(?:^|\s)--staged(?:\s|$)/.test(t);
  return true;
}

// The directories `command`'s segments run in that drop a staged squash. See gitDirs and
// dropsSquash.
function unsquashDirs(command, cwd) {
  return gitDirs(command, cwd, UNSQUASH_VERBS, dropsSquash);
}

// How a `git reset` segment changes the index. 'rerecord': it moves HEAD and keeps the
// undone commits' changes, so a later commit repeats lines that those commits already
// counted. That is `--soft` with a rev, or `--mixed` or no mode with a first non-option
// word that is a revision and not an existing path: it holds `~`, `^` or `@{`, or is a
// 7 to 40 character hex sha, or `git rev-parse --verify --quiet <word>^{commit}` resolves
// it in `dir`. 'keep': it only unstages (`git reset`, `git reset HEAD`, a path list, or
// any form with a `--` separator). 'clear': `--hard`, `--keep` or `--merge` throw the
// changes away.
function resetKind(text, dir, run) {
  const words = blankQuotes(text).replace(/^.*?\bgit\b(?:\s+-[Cc]\s+(?:"[^"]*"|'[^']*'|\S+))*\s+reset\b/, '').trim().split(/\s+/).filter(Boolean);
  if (words.some((w) => w === '--hard' || w === '--keep' || w === '--merge')) return 'clear';
  const dash = words.indexOf('--');
  const before = dash < 0 ? words : words.slice(0, dash);
  const first = before.find((w) => !w.startsWith('-'));
  if (dash >= 0 || !first || first === 'HEAD') return 'keep';
  if (words.includes('--soft')) return 'rerecord';
  if (dir && fs.existsSync(path.join(dir, first))) return 'keep';
  if (/[~^]|@\{/.test(first) || /^[0-9a-f]{7,40}$/i.test(first)) return 'rerecord';
  try {
    run(['rev-parse', '--verify', '--quiet', `${first}^{commit}`], dir);
    return 'rerecord';
  } catch {
    return 'keep';
  }
}

// The `git commit` and index-changing segments of `command`, in order, as
// [{ kind: 'commit' | 'rerecord' | 'clear', dir }]. extract.js walks them to find the
// commits that follow a reset that moved HEAD. Segments that keep the state (an unstage)
// are left out.
function resetEvents(command, cwd, run = defaultRun) {
  const verbs = ['commit', 'reset', 'checkout', 'switch', 'stash', 'merge', 'restore'];
  const events = [];
  for (const { dir, text, verb } of gitSegments(command, cwd, verbs, () => true)) {
    const t = blankQuotes(text);
    if (verb === 'commit') events.push({ kind: 'commit', dir });
    else if (verb === 'reset') {
      const kind = resetKind(text, dir, run);
      if (kind !== 'keep') events.push({ kind, dir });
    } else if (verb === 'merge') {
      if (/(?:^|\s)--abort(?:\s|$)/.test(t)) events.push({ kind: 'clear', dir });
    } else if (verb === 'restore') {
      if (/(?:^|\s)--staged(?:\s|$)/.test(t)) events.push({ kind: 'clear', dir });
    } else events.push({ kind: 'clear', dir });
  }
  return events;
}

// The directories `command`'s `git merge --squash` calls run in, without those where a
// later segment of the same command drops the squash (`git merge --squash x || git merge
// --abort`). Quoted text is blanked before the option test, so `git merge -m "no
// --squash"` is not a squash merge.
function squashDirs(command, cwd) {
  const isSquash = (text, verb) => verb === 'merge' && /(?:^|\s)--squash(?:\s|$)/.test(blankQuotes(text));
  const dirs = [];
  for (const { dir, text, verb } of gitSegments(command, cwd, UNSQUASH_VERBS, (t, v) => isSquash(t, v) || dropsSquash(t, v))) {
    const at = dirs.indexOf(dir);
    if (isSquash(text, verb)) {
      if (at < 0) dirs.push(dir);
    } else if (at >= 0) dirs.splice(at, 1);
  }
  return dirs;
}

// `opts.input` is written to the command's stdin (patch-id and check-attr read their
// input from it). Without it stdin is closed. `opts.encoding` 'buffer' returns a Buffer,
// so bytes that are not UTF-8 pass through unchanged.
function defaultRun(args, cwd, opts = {}) {
  const { input, encoding = 'utf8' } = opts;
  return execFileSync('git', args, { cwd, input, encoding, timeout: 5000, maxBuffer: 256 << 20, stdio: [input === undefined ? 'ignore' : 'pipe', 'pipe', 'pipe'] });
}

// Set once git is known to be missing or to be the macOS developer-tools stub. Every
// later resolveCommits call returns without spawning git, so the stub does not open
// its install dialog again.
let gitUnavailable = false;

// True when a failed git call can pass on a later try: execFileSync kills a call that
// passes `timeout` and sets `code` ETIMEDOUT and `signal` SIGTERM on the error.
function isTimeout(err) {
  return !!err && (err.code === 'ETIMEDOUT' || !!err.signal);
}

// True when a failed git call means git itself cannot run: no `git` on PATH (ENOENT),
// or the macOS stub that exits 1 and prints an xcode-select or xcrun message.
// Node gives a missing `cwd` the same ENOENT error as a missing binary, so ENOENT
// counts only when `cwd` exists.
function isGitUnavailable(err, cwd) {
  if (!err) return false;
  if (err.code === 'ENOENT') return fs.existsSync(cwd);
  return err.status === 1 && /xcrun: error|xcode-select|developer tools/i.test(String(err.stderr || ''));
}

// Parses NUL-separated numstat entries: `added\tremoved\tpath`, or
// `added\tremoved\t` followed by the old and new path for a rename. `files` name a
// renamed file by its new path. Binary files (`-`) and lockfiles count 0. `stats` holds
// the counted lines per file, so a caller can take a file out of the totals later.
function parseNumstat(stat) {
  let added = 0;
  let removed = 0;
  const files = [];
  const stats = [];
  for (let i = 0; i < stat.length; i++) {
    const m = /^(\d+|-)\t(\d+|-)\t([\s\S]*)$/.exec(stat[i]);
    if (!m) continue;
    let file = m[3];
    if (!file) {
      file = stat[i + 2];
      i += 2;
    }
    files.push(file);
    const zero = m[1] === '-' || LOCKFILES.has(path.basename(file));
    const a = zero ? 0 : Number(m[1]);
    const r = zero ? 0 : Number(m[2]);
    stats.push({ file, added: a, removed: r });
    added += a;
    removed += r;
  }
  return { added, removed, files, stats };
}

// Parses the `log -z --numstat` output into rows (each with `stats`, see parseNumstat).
// With -z, each record is `\x1e<header>\0\n` followed by the numstat entries.
function parseLog(out, toplevel, repo) {
  const rows = [];
  for (const rec of out.split('\x1e')) {
    if (!rec.trim()) continue;
    const nul = rec.indexOf('\0');
    const head = nul < 0 ? rec : rec.slice(0, nul);
    const stat = nul < 0 ? [] : rec.slice(nul + 1).replace(/^\n/, '').split('\0');
    const [sha, parents, ct, at, authorEmail, committerEmail, subject, gs] = head.split('\x1f');
    const { added, removed, files, stats } = parseNumstat(stat);
    rows.push({ sha, parent: parents.split(' ')[0] || null, added, removed, files, stats, repo, toplevel, ct: Number(ct), authorTime: Number(at), authorEmail, committerEmail, subject, gs });
  }
  return rows;
}

// Runs `fn` for a step that only adds a field to a row. A missing git is thrown, so
// resolveCommits classifies it. Any other failure, ENOBUFS included (its error also
// carries a signal), gives `fallback`, and the row keeps its other fields. A timeout is
// thrown too, unless `onTimeout` is given: then it is called and `fallback` is returned,
// so the caller can keep the row and report the result as transient.
function soft(fn, fallback, cwd, onTimeout) {
  try {
    return fn();
  } catch (err) {
    if (err && err.code === 'ENOBUFS') return fallback;
    if (isTimeout(err) && onTimeout) {
      onTimeout();
      return fallback;
    }
    if (isTimeout(err) || isGitUnavailable(err, cwd)) throw err;
    return fallback;
  }
}

// Map of commit sha to `git patch-id --stable`, from one `log -p` over `shas` piped into
// `patch-id`. A commit with an empty patch has no entry.
function patchIds(shas, cwd, run) {
  const ids = new Map();
  if (!shas.length) return ids;
  // The patch is read and passed on as a Buffer, so non-UTF-8 bytes are not folded
  // together. `--no-textconv` keeps a textconv filter from rewriting the diff.
  const patch = run(['log', '--no-walk=unsorted', '-p', '--no-textconv', '--format=commit %H', '--end-of-options', ...shas, '--'], cwd, { encoding: 'buffer' });
  if (!patch || !patch.length) return ids;
  const out = run(['patch-id', '--stable'], cwd, { input: patch });
  for (const line of out.split('\n')) {
    const [id, sha] = line.split(' ');
    if (id && sha) ids.set(sha, id);
  }
  return ids;
}

// The files of `row` that `.gitattributes` marks linguist-generated or linguist-vendored.
// Attributes come from the commit's own tree (`check-attr --source`, git 2.40+). Where
// that option is unknown, the working tree's attributes are used. If that fails too, no
// file is generated. Paths are relative to the repository root, so the call runs there.
function generatedFiles(row, run) {
  if (!row.files.length) return [];
  const attrs = ['linguist-generated', 'linguist-vendored', '--stdin'];
  const input = row.files.join('\0') + '\0';
  const read = (args) => {
    const out = run(['check-attr', '-z', ...args], row.toplevel, { input }).split('\0');
    const set = new Set();
    for (let i = 0; i + 2 < out.length; i += 3) if (out[i + 2] === 'set' || out[i + 2] === 'true') set.add(out[i]);
    return row.files.filter((f) => set.has(f));
  };
  try {
    return read([`--source=${row.sha}`, ...attrs]);
  } catch (err) {
    if (isTimeout(err) && err.code !== 'ENOBUFS') throw err;
    return read(attrs);
  }
}

// What HEAD's reflog says `row` replaced: the entry for row.sha whose subject starts with
// `commit (amend)`, and the entry after it (the older HEAD). Returns the numstat of
// `git diff <original> <row.sha>`, with the same zero rules as parseLog and without the
// row's generated files, or null when the reflog does not name the original.
function amendDelta(row, reflog, run) {
  const i = reflog.findIndex((e) => e.sha === row.sha && e.subject.startsWith('commit (amend)'));
  const orig = i >= 0 ? reflog[i + 1] : null;
  if (!orig) return null;
  return { sha: orig.sha, ...diffTotals(orig.sha, row.sha, row, run) };
}

// The numstat of `git diff <from> <to>` with the zero rules of parseLog, without the
// generated files of `row`.
function diffTotals(from, to, row, run) {
  const out = run(['diff', '--numstat', '-z', '-M', from, to, '--'], row.toplevel);
  const { stats } = parseNumstat(out.split('\0'));
  const kept = stats.filter((s) => !row.generated.includes(s.file));
  return { added: kept.reduce((n, s) => n + s.added, 0), removed: kept.reduce((n, s) => n + s.removed, 0) };
}

// Marks the commits that followed a `git reset` which moved HEAD (`since` ms is the
// reset call's start) as `squash`, because they re-record work that the undone commits
// already counted. The reflog gives the order: the oldest `reset: moving to` entry since
// `since` starts the sequence, the entry before it is the pre-reset HEAD, and only
// commits newer than that entry are marked, so a commit made before the reset in the
// same command stays. The newest marked commit gets `rerecordDelta`, the numstat of
// `git diff <pre-reset HEAD> <it>`, which is the work the sequence added. With no such
// reflog entry in a removed checkout (`dir` is gone, so its reflog went with it) every
// row is marked and none has a delta. With no such entry in a checkout that exists, the
// reset did not move HEAD (it failed, or git has no record of it), so no row is marked.
function markRerecord(rows, since, hi, cwd, run, dirExists, onTimeout) {
  const lo = Math.floor(since / 1000) - 1;
  let timedOut = false;
  const log = soft(() => run(['log', '-g', 'HEAD', '--date=unix', '-n', '300', '--format=%H%x1f%gs%x1f%gd'], cwd), '', cwd, () => { timedOut = true; onTimeout(); });
  // A timed-out read leaves every row unmarked: without the reflog, nothing says which
  // commits followed the reset.
  if (timedOut) return;
  const entries = log
    .split('\n').filter(Boolean).map((l) => {
      const [sha, gs = '', gd = ''] = l.split('\x1f');
      return { sha, gs, at: Number((/@\{(\d+)\}/.exec(gd) || [])[1]) };
    });
  let r = -1;
  entries.forEach((e, i) => { if (e.gs.startsWith('reset: moving to') && e.at >= lo && e.at <= hi) r = i; });
  if (r < 0) {
    if (!dirExists) for (const row of rows) row.squash = true;
    return;
  }
  const indexOf = (sha) => entries.findIndex((e) => e.sha === sha && /^(?:commit|cherry-pick|rebase|revert)/.test(e.gs));
  const marked = [];
  for (const row of rows) {
    const i = indexOf(row.sha);
    if (i < 0 || i >= r) continue;
    row.squash = true;
    marked.push(row);
  }
  // The sequence's last commit is found by ancestry, because its commits can share one
  // committer second: it is the marked row that no other marked row lists as its parent.
  // When the sequence branched, the commit HEAD holds after the call (the newest reflog
  // commit entry) decides. With neither, no row gets a delta and all count 0.
  const parents = new Set(marked.map((m) => m.parent));
  const tips = marked.filter((m) => !parents.has(m.sha));
  let last = tips.length === 1 ? tips[0] : null;
  if (!last && tips.length > 1) {
    const head = entries.find((e) => /^(?:commit|cherry-pick|rebase|revert)/.test(e.gs))?.sha;
    last = tips.find((m) => m.sha === head) ?? null;
  }
  const pre = entries[r + 1]?.sha;
  if (last && pre) last.rerecordDelta = soft(() => diffTotals(pre, last.sha, last, run), undefined, cwd, onTimeout);
  if (last && last.rerecordDelta === undefined) delete last.rerecordDelta;
}

const cache = new Map();
// Repository root by directory, so a call in a directory already seen skips
// `rev-parse`. A directory with no usable repository holds null.
const toplevels = new Map();

// Test hook: forgets the caches and the gitUnavailable flag.
function resetCommitState() {
  cache.clear();
  toplevels.clear();
  gitUnavailable = false;
}

// The repository root of `cwd`, or null when `cwd` holds no usable repository. The
// null is cached. A timeout or a missing git is thrown and not cached.
function topOf(cwd, run) {
  if (toplevels.has(cwd)) return toplevels.get(cwd);
  try {
    const top = run(['rev-parse', '--show-toplevel'], cwd).trim();
    toplevels.set(cwd, top);
    return top;
  } catch (err) {
    if (!isTimeout(err) && !isGitUnavailable(err, cwd)) toplevels.set(cwd, null);
    throw err;
  }
}

// The repository root of existing folder `dir`, from the same cache resolveCommits
// fills, or null when `dir` is gone, holds no repository, or git failed. Never throws,
// and never sets the gitUnavailable flag, which only resolveCommits sets.
function checkoutTop(dir) {
  try {
    return typeof dir === 'string' && fs.existsSync(dir) ? topOf(dir, defaultRun) : null;
  } catch {
    return null;
  }
}

// The commits made in folder `dir` between `t0` and `t1` (ms), as { rows, transient }.
// When `dir` is gone (a removed worktree), the repo findRepo maps it to is used.
// `git log HEAD` is read first, so a sibling worktree's commit is not taken for this
// one. Only when HEAD has no commit in the window does `--all` run, which finds a
// commit on another branch (a `git checkout` after the commit). A commit whose author
// time is outside the window is a rewritten copy (rebase, cherry-pick and pull
// --rebase keep the author time), so it is dropped unless the command is an amend,
// whose commit keeps the amended commit's author time. When the command names a commit
// subject, only commits with that subject are returned and they carry `named: true`.
// `failed` (the call's result had is_error) skips the `--all` query.
// `amend` is set only on rows from the HEAD query or named rows, because an unnamed
// row from `--all` may belong to another session.
// Nothing throws. A timeout or signal gives rows [] with transient true and is not
// cached, so extract.js can mark the row set incomplete. Git missing gives rows [] and
// stops every later spawn. Any other failure (not a repository, dubious ownership)
// gives rows [] and is cached. A repeat call with the same dir and window is answered
// from the cache, because rowstore re-extracts a live transcript on every change.
function resolveCommits({ dir, t0, t1, command, failed = false, rerecordSince = null, run = defaultRun }) {
  if (gitUnavailable) return { rows: [], transient: false };
  const key = `${dir}\0${t0}\0${t1}\0${command}\0${failed}\0${rerecordSince}`;
  if (cache.has(key)) return cache.get(key);
  let rows = [];
  let cwd = null;
  let incomplete = false;
  try {
    cwd = fs.existsSync(dir) ? dir : findRepo(dir);
    // findRepo caches paths, so its answer can be a folder deleted since.
    const toplevel = cwd && fs.existsSync(cwd) ? topOf(cwd, run) : null;
    if (toplevel) {
      // A bare `@N` is not read as an epoch by git for small N, so the dates carry `+0000`.
      const lo = Math.floor(t0 / 1000) - 1;
      const hi = Math.ceil(t1 / 1000) + 1;
      const { amendAt, firstRewrite } = amendInfo(command);
      const amend = amendAt.length > 0;
      const keepsAt = keepsAuthorTime(command);
      const repo = findRepo(toplevel);
      // `rev` is HEAD or '--all'. `--end-of-options` and the trailing `--` keep a file or
      // branch named HEAD from being read as the revision. `--all` skips the stash, whose
      // commits are not made by `git commit`.
      // `rev` 'reflog' reads the checkout's own HEAD reflog (`git log -g HEAD`).
      const query = (rev) => {
        const out = run(['log', ...(rev === '--all' ? ['--exclude=refs/stash', '--all'] : []), ...(rev === 'reflog' ? ['-g'] : []), '--no-merges', '-M', '-z',
          `--since=@${lo} +0000`, `--until=@${hi} +0000`, '--format=%x1e%H%x1f%P%x1f%ct%x1f%at%x1f%ae%x1f%ce%x1f%s' + (rev === 'reflog' ? '%x1f%gs' : ''), '--numstat',
          '--end-of-options', ...(rev === '--all' ? [] : [rev === 'reflog' ? 'HEAD' : rev]), '--'], cwd);
        const seen = new Set();
        // A reflog entry creates a commit when its subject starts with `commit` (amend and
        // initial included), `cherry-pick`, `rebase` or `revert`. A fast-forward, pull,
        // checkout or reset entry only moves HEAD onto a commit made elsewhere.
        const makes = (r) => rev !== 'reflog' || /^(?:commit|cherry-pick|rebase|revert)/.test(r.gs ?? '');
        const inWindow = parseLog(out, toplevel, repo).filter((r) => {
          if (!makes(r)) return false;
          if (r.ct < lo || r.ct > hi || seen.has(r.sha)) return false;
          seen.add(r.sha);
          return true;
        });
        // Each --amend segment exempts one commit from the author-time filter. An amend
        // that runs before a rebase or pull made the oldest rewritten commit by committer
        // time. A lone amend, or one after a rebase or pull, made the newest.
        const old = inWindow.filter((r) => r.authorTime < lo || r.authorTime > hi);
        const exempt = new Set();
        for (const at of amendAt) {
          const pool = old.filter((r) => !exempt.has(r.sha)).sort((a, b) => (firstRewrite >= 0 && at < firstRewrite ? a.ct - b.ct : b.ct - a.ct));
          if (pool.length) exempt.add(pool[0].sha);
        }
        // A commit whose author time is outside the window is a copy that a rebase or
        // cherry-pick made. It is kept as a `rewrite` row with its `committerEmail`.
        // lineRows decides whether it counts: it drops a copy whose original is counted
        // and one whose author never committed in the repo.
        const keptRows = [];
        for (const r of inWindow) {
          if (keepsAt || exempt.has(r.sha) || (r.authorTime >= lo && r.authorTime <= hi)) keptRows.push(r);
          else keptRows.push({ ...r, rewrite: true });
        }
        return keptRows;
      };
      const fromHead = query('HEAD');
      // A rewrite row (a rebased or cherry-picked copy) does not stop the later queries,
      // because the call's own commit may be on no ref and rewrite rows alone are only
      // copies of earlier work. `good` is true when a query found a non-rewrite row.
      const good = (list) => list.some((r) => !r.rewrite);
      let found = fromHead;
      const logOnly = new Set();
      // The checkout's own HEAD reflog is read next to HEAD for every call that did not
      // fail and whose folder exists. It lists commits that a later amend or rebase took
      // off every ref, and it holds no sibling worktree's commit. A removed worktree
      // takes its reflog with it. Rows found only there carry `fromReflog`.
      if (!failed && fs.existsSync(dir)) {
        const inHead = new Set(fromHead.map((r) => r.sha));
        const extra = soft(() => query('reflog'), [], cwd).filter((r) => !inHead.has(r.sha));
        for (const r of extra) logOnly.add(r.sha);
        found = [...fromHead, ...extra];
      }
      // A failed call may still have committed (`git commit -m x && npm test`), so HEAD
      // is read. `--all` is skipped, because it could return a sibling worktree's commit.
      if (!good(found) && !failed) {
        const all = query('--all');
        if (good(all)) found = all;
      }
      const isNamed = (r) => !!r.subject && String(command).includes(r.subject);
      const named = found.filter(isNamed);
      const picked = named.length ? named : found;
      // A timeout in a step that only adds a field keeps the rows with that field's
      // fallback and makes the result transient, so extract.js retries it later.
      const incompleteStep = () => { incomplete = true; };
      const ids = soft(() => patchIds(picked.map((r) => r.sha), cwd, run), new Map(), cwd, incompleteStep);
      const headShas = new Set(fromHead.map((r) => r.sha));
      let reflog = null;
      rows = picked.map(({ ct, stats, gs, ...row }) => {
        const isNamedRow = named.length > 0;
        const out = { ...row, amend: amend && (good(fromHead) || isNamedRow || logOnly.has(row.sha)) };
        // The folder was gone, so the log was read from the main checkout (findRepo).
        if (!fs.existsSync(dir)) out.fallback = true;
        if (isNamedRow) out.named = true;
        out.patchId = ids.get(row.sha) ?? null;
        out.generated = soft(() => generatedFiles(row, run), [], cwd, incompleteStep);
        const skip = stats.filter((s) => out.generated.includes(s.file));
        out.added -= skip.reduce((n, s) => n + s.added, 0);
        out.removed -= skip.reduce((n, s) => n + s.removed, 0);
        if (logOnly.has(row.sha)) out.fromReflog = true;
        out.amendOf = null;
        if (out.amend && headShas.has(row.sha)) {
          out.amendOf = soft(() => {
            reflog ??= run(['log', '-g', 'HEAD', '-n', '20', '--format=%H%x1f%gs'], cwd).split('\n').filter(Boolean).map((l) => {
              const [sha, subject = ''] = l.split('\x1f');
              return { sha, subject };
            });
            return amendDelta(out, reflog, run);
          }, null, cwd, incompleteStep);
        }
        return out;
      });
      if (rerecordSince != null && rows.length) markRerecord(rows, rerecordSince, hi, cwd, run, fs.existsSync(dir), incompleteStep);
    }
  } catch (err) {
    // execFileSync kills a call that passes maxBuffer, so the error also carries a signal.
    // A patch too large to read will be as large on a retry, so it is permanent.
    if (err && err.code === 'ENOBUFS') {
      console.warn(`cc-dashboard: git output in ${dir} exceeded the buffer, commits skipped`);
    } else {
      if (isTimeout(err)) return { rows: [], transient: true };
      if (isGitUnavailable(err, cwd)) {
        gitUnavailable = true;
        return { rows: [], transient: false };
      }
    }
    rows = [];
  }
  const result = { rows, transient: incomplete };
  if (!incomplete) cache.set(key, result);
  return result;
}

module.exports = { isCommitCommand, commitDirs, squashDirs, resetEvents, unsquashDirs, checkoutTop, resolveCommits, resetCommitState };
