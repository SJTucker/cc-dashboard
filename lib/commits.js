'use strict';

// Finds the commits a Bash `git commit` call created, so extract.js can count the
// lines of code written through heredocs and `sed -i`, which Edit and Write results
// never show. The transcript's own commit output is never parsed: rtk rewrites it
// to `ok N files changed` or just `ok`. The commits are read back from git instead.

const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');
const { bashGroup } = require('./transcript-lines');
const { findRepo } = require('./repo');

// Lines of these files are generated by tools, so they count 0.
const LOCKFILES = new Set(['package-lock.json', 'pnpm-lock.yaml', 'yarn.lock', 'Cargo.lock']);

// The parts of a command that run one after another, split on && || ; | and newlines.
// Each part is { text, open, close }: `text` without its leading `(` and trailing `)`,
// `open` the count of leading `(` and `close` the count of trailing `)`.
function parts(command) {
  return String(command || '').split(/&&|\|\||[;|\n]/).map((raw) => {
    const s = raw.trim();
    const open = /^[\s(]*/.exec(s)[0].split('(').length - 1;
    const close = /\)*$/.exec(s)[0].length;
    return { text: s.replace(/^[\s(]+/, '').replace(/\)+$/, '').trim(), open, close };
  }).filter((p) => p.text);
}

function segments(command) {
  return parts(command).map((p) => p.text);
}

// Replaces quoted text with `""`, so words inside a commit message are not read as options.
function blankQuotes(command) {
  return String(command || '').replace(/"(?:[^"\\]|\\.)*"|'[^']*'/g, '""');
}

// The number of `git commit --amend` segments in `command`, and the number of rebase or
// pull segments that come before the first of them. Quoted text is blanked first, so
// `-m "docs: explain --amend"` does not count.
function amendInfo(command) {
  const segs = segments(blankQuotes(command));
  const amendAt = [];
  let firstRewrite = -1;
  segs.forEach((s, i) => {
    const group = bashGroup(s);
    if (group === 'git commit' && /(?:^|\s)--amend(?:\s|$)/.test(s)) amendAt.push(i);
    if ((group === 'git rebase' || group === 'git pull') && firstRewrite < 0) firstRewrite = i;
  });
  return { amendAt, firstRewrite };
}

// True when a `git commit` segment keeps an older author time on purpose: --date,
// -C/-c/--reuse-message/--reedit-message (the words after `commit`, not `git -C <path>`).
function keepsAuthorTime(command) {
  return segments(blankQuotes(command)).some((s) => {
    if (bashGroup(s) !== 'git commit') return false;
    const m = COMMIT_WORDS.exec(s);
    return !!m && /(?:^|\s)(?:--date(?:=|\s|$)|-[Cc]|--reuse-message|--reedit-message)/.test(m[2]);
  });
}

// True when any segment of `command` is a `git commit` (also through rtk or `git -C`).
function isCommitCommand(command) {
  return segments(command).some((s) => bashGroup(s) === 'git commit');
}

// The first word of `text` with one layer of quotes removed, and `~` expanded.
function firstPath(text) {
  const m = /^(?:"([^"]*)"|'([^']*)'|(\S+))/.exec(text.trim());
  if (!m) return null;
  const p = m[1] ?? m[2] ?? m[3];
  if (p === '~' || p.startsWith('~/')) return path.join(os.homedir(), p.slice(1));
  return p;
}

// `git [-C path | -c k=v]... commit` in a segment: [1] holds the options before `commit`,
// [2] the words after it. A `-C` in [2] is the reuse-message option, not a directory.
const COMMIT_WORDS = /(?:^|\s)git\s+((?:-[Cc]\s+(?:"[^"]*"|'[^']*'|\S+)\s+)*)commit(?:\s+([\s\S]*))?$/;

// The directories `command`'s `git commit` calls run in, one per call in order, without
// duplicates. Each call's directory is the last `cd` before it, then its own `git -C`,
// resolved against `cwd`. A `(` pushes the current directory and a `)` pops it, so the
// `cd` in `(cd /a) && git commit` does not reach the commit. Paths that do not resolve
// to an absolute path are left out.
function commitDirs(command, cwd) {
  const stack = [cwd];
  const dirs = [];
  const resolve = (dir, target) => (dir || path.isAbsolute(target) ? path.resolve(dir || '/', target) : null);
  for (const { text, open, close } of parts(command)) {
    for (let i = 0; i < open; i++) stack.push(stack[stack.length - 1]);
    const cd = /^cd\s+(.+)$/.exec(text);
    if (cd) {
      const target = firstPath(cd[1]);
      if (target) stack[stack.length - 1] = resolve(stack[stack.length - 1], target);
    } else if (bashGroup(text) === 'git commit') {
      let dir = stack[stack.length - 1];
      const m = COMMIT_WORDS.exec(text);
      for (const c of m ? m[1].matchAll(/-C\s+("[^"]*"|'[^']*'|\S+)/g) : []) {
        const target = firstPath(c[1]);
        if (target) dir = resolve(dir, target);
      }
      if (dir && path.isAbsolute(dir) && !dirs.includes(dir)) dirs.push(dir);
    }
    for (let i = 0; i < close && stack.length > 1; i++) stack.pop();
  }
  return dirs;
}

// Kept for lib/extract.js until it reads every directory from commitDirs.
const commitDir = (command, cwd) => commitDirs(command, cwd)[0] ?? null;

function defaultRun(args, cwd) {
  return execFileSync('git', args, { cwd, encoding: 'utf8', timeout: 5000, maxBuffer: 256 << 20, stdio: ['ignore', 'pipe', 'pipe'] });
}

// Set once git is known to be missing or to be the macOS developer-tools stub. Every
// later resolveCommits call returns without spawning git, so the stub does not open
// its install dialog again.
let gitUnavailable = false;

// True when a failed git call can pass on a later try: execFileSync kills a call that
// passes `timeout` and sets `code` ETIMEDOUT and `signal` SIGTERM on the error.
function isTimeout(err) {
  return !!err && (err.code === 'ETIMEDOUT' || !!err.signal);
}

// True when a failed git call means git itself cannot run: no `git` on PATH (ENOENT),
// or the macOS stub that exits 1 and prints an xcode-select or xcrun message.
// Node gives a missing `cwd` the same ENOENT error as a missing binary, so ENOENT
// counts only when `cwd` exists.
function isGitUnavailable(err, cwd) {
  if (!err) return false;
  if (err.code === 'ENOENT') return fs.existsSync(cwd);
  return err.status === 1 && /xcrun: error|xcode-select|developer tools/i.test(String(err.stderr || ''));
}

// Parses the `log -z --numstat` output into rows. `files` are relative to `toplevel`
// and name a renamed file by its new path. Binary files (`-`) and lockfiles count 0.
// With -z, each record is `\x1e<header>\0\n` followed by NUL-terminated numstat entries:
// `added\tremoved\tpath\0`, or `added\tremoved\t\0old\0new\0` for a rename.
function parseLog(out, toplevel, repo) {
  const rows = [];
  for (const rec of out.split('\x1e')) {
    if (!rec.trim()) continue;
    const nul = rec.indexOf('\0');
    const head = nul < 0 ? rec : rec.slice(0, nul);
    const stat = nul < 0 ? [] : rec.slice(nul + 1).replace(/^\n/, '').split('\0');
    const [sha, parents, ct, at, authorEmail, subject] = head.split('\x1f');
    let added = 0;
    let removed = 0;
    const files = [];
    for (let i = 0; i < stat.length; i++) {
      const m = /^(\d+|-)\t(\d+|-)\t(.*)$/.exec(stat[i]);
      if (!m) continue;
      let file = m[3];
      if (!file) {
        file = stat[i + 2];
        i += 2;
      }
      files.push(file);
      if (m[1] === '-' || LOCKFILES.has(path.basename(file))) continue;
      added += Number(m[1]);
      removed += Number(m[2]);
    }
    rows.push({ sha, parent: parents.split(' ')[0] || null, added, removed, files, repo, toplevel, ct: Number(ct), authorTime: Number(at), authorEmail, subject });
  }
  return rows;
}

const cache = new Map();
// Repository root by directory, so a call in a directory already seen skips
// `rev-parse`. A directory with no usable repository holds null.
const toplevels = new Map();

// Test hook: forgets the caches and the gitUnavailable flag.
function resetCommitState() {
  cache.clear();
  toplevels.clear();
  gitUnavailable = false;
}

// The repository root of `cwd`, or null when `cwd` holds no usable repository. The
// null is cached. A timeout or a missing git is thrown and not cached.
function topOf(cwd, run) {
  if (toplevels.has(cwd)) return toplevels.get(cwd);
  try {
    const top = run(['rev-parse', '--show-toplevel'], cwd).trim();
    toplevels.set(cwd, top);
    return top;
  } catch (err) {
    if (!isTimeout(err) && !isGitUnavailable(err, cwd)) toplevels.set(cwd, null);
    throw err;
  }
}

// The commits made in folder `dir` between `t0` and `t1` (ms), as { rows, transient }.
// When `dir` is gone (a removed worktree), the repo findRepo maps it to is used.
// `git log HEAD` is read first, so a sibling worktree's commit is not taken for this
// one. Only when HEAD has no commit in the window does `--all` run, which finds a
// commit on another branch (a `git checkout` after the commit). A commit whose author
// time is outside the window is a rewritten copy (rebase, cherry-pick and pull
// --rebase keep the author time), so it is dropped unless the command is an amend,
// whose commit keeps the amended commit's author time. When the command names a commit
// subject, only commits with that subject are returned and they carry `named: true`.
// `failed` (the call's result had is_error) skips the `--all` query.
// `amend` is set only on rows from the HEAD query or named rows, because an unnamed
// row from `--all` may belong to another session.
// Nothing throws. A timeout or signal gives rows [] with transient true and is not
// cached, so extract.js can mark the row set incomplete. Git missing gives rows [] and
// stops every later spawn. Any other failure (not a repository, dubious ownership)
// gives rows [] and is cached. A repeat call with the same dir and window is answered
// from the cache, because rowstore re-extracts a live transcript on every change.
function resolveCommits({ dir, t0, t1, command, failed = false, run = defaultRun }) {
  if (gitUnavailable) return { rows: [], transient: false };
  const key = `${dir}\0${t0}\0${t1}\0${command}\0${failed}`;
  if (cache.has(key)) return cache.get(key);
  let rows = [];
  let cwd = null;
  try {
    cwd = fs.existsSync(dir) ? dir : findRepo(dir);
    // findRepo caches paths, so its answer can be a folder deleted since.
    const toplevel = cwd && fs.existsSync(cwd) ? topOf(cwd, run) : null;
    if (toplevel) {
      // A bare `@N` is not read as an epoch by git for small N, so the dates carry `+0000`.
      const lo = Math.floor(t0 / 1000) - 1;
      const hi = Math.ceil(t1 / 1000) + 1;
      const { amendAt, firstRewrite } = amendInfo(command);
      const amend = amendAt.length > 0;
      const keepsAt = keepsAuthorTime(command);
      const repo = findRepo(toplevel);
      // `rev` is HEAD or '--all'. `--end-of-options` and the trailing `--` keep a file or
      // branch named HEAD from being read as the revision. `--all` skips the stash, whose
      // commits are not made by `git commit`.
      const query = (rev) => {
        const out = run(['log', ...(rev === '--all' ? ['--exclude=refs/stash', '--all'] : []), '--no-merges', '-M', '-z',
          `--since=@${lo} +0000`, `--until=@${hi} +0000`, '--format=%x1e%H%x1f%P%x1f%ct%x1f%at%x1f%ae%x1f%s', '--numstat',
          '--end-of-options', ...(rev === '--all' ? [] : [rev]), '--'], cwd);
        const seen = new Set();
        const inWindow = parseLog(out, toplevel, repo).filter((r) => {
          if (r.ct < lo || r.ct > hi || seen.has(r.sha)) return false;
          seen.add(r.sha);
          return true;
        });
        // Each --amend segment exempts one commit from the author-time filter. An amend
        // that runs before every rebase or pull made the oldest rewritten commit by
        // committer time, and one that runs after made the newest.
        const old = inWindow.filter((r) => r.authorTime < lo || r.authorTime > hi);
        const exempt = new Set();
        for (const at of amendAt) {
          const pool = old.filter((r) => !exempt.has(r.sha)).sort((a, b) => (firstRewrite < 0 || at < firstRewrite ? a.ct - b.ct : b.ct - a.ct));
          if (pool.length) exempt.add(pool[0].sha);
        }
        return inWindow.filter((r) => keepsAt || exempt.has(r.sha) || (r.authorTime >= lo && r.authorTime <= hi));
      };
      const fromHead = query('HEAD');
      // A failed call may still have committed (`git commit -m x && npm test`), so HEAD
      // is read. `--all` is skipped, because it could return a sibling worktree's commit.
      const found = fromHead.length || failed ? fromHead : query('--all');
      const isNamed = (r) => !!r.subject && String(command).includes(r.subject);
      const named = found.filter(isNamed);
      rows = (named.length ? named : found).map(({ ct, ...row }) => {
        const isNamedRow = named.length > 0;
        const out = { ...row, amend: amend && (fromHead.length > 0 || isNamedRow) };
        if (isNamedRow) out.named = true;
        return out;
      });
    }
  } catch (err) {
    // execFileSync kills a call that passes maxBuffer, so the error also carries a signal.
    // A patch too large to read will be as large on a retry, so it is permanent.
    if (err && err.code === 'ENOBUFS') {
      console.warn(`cc-dashboard: git output in ${dir} exceeded the buffer, commits skipped`);
    } else {
      if (isTimeout(err)) return { rows: [], transient: true };
      if (isGitUnavailable(err, cwd)) {
        gitUnavailable = true;
        return { rows: [], transient: false };
      }
    }
    rows = [];
  }
  const result = { rows, transient: false };
  cache.set(key, result);
  return result;
}

module.exports = { isCommitCommand, commitDir, commitDirs, resolveCommits, resetCommitState };
